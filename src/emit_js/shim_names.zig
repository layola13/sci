/// Host shims whose JS lowering allocates a fresh linear-memory block.
pub fn isAllocatorShim(name: []const u8) bool {
    return std.mem.eql(u8, name, "mmap") or
        std.mem.eql(u8, name, "dlopen") or
        std.mem.eql(u8, name, "dlsym");
}

