            \\int32_t sa_task_current(uint64_t *);
            \\int32_t sa_task_live_count(uint64_t *);
            \\int32_t sa_task_deadlock_guard_arm(void);
            \\int32_t sa_task_net_wait(uint64_t, uint32_t, int64_t, uint32_t *);
